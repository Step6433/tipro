"""Export a portable, empty PostgreSQL schema. Never exports account/payment data."""
import argparse
import asyncio
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

async def export(args):
    import asyncpg
    from sqlalchemy.engine import make_url
    from app.config import get_settings
    url = make_url(get_settings().database_url)
    binary = Path(args.bin_dir) / 'pg_dump' if args.bin_dir else None
    if binary is None:
        installed = shutil.which('pg_dump')
        binary = Path(installed) if installed else Path('/private/tmp/tipro-postgres18/bin/pg_dump')
    if not binary.is_file():
        raise RuntimeError('pg_dump not found; pass --bin-dir or set TIPRO_PG_BIN.')
    conn = await asyncpg.connect(host=url.host, port=url.port or 5432, user=url.username,
                                 password=url.password, database=url.database)
    try:
        revisions = await conn.fetch('SELECT version_num FROM alembic_version ORDER BY version_num')
    finally:
        await conn.close()
    if not revisions or any(not re.fullmatch(r'[a-zA-Z0-9_]+', r['version_num']) for r in revisions):
        raise RuntimeError('Apply migrations before exporting the schema.')
    # Credentials are passed only in the subprocess environment, never in CLI arguments or output.
    command = [str(binary), '--schema-only', '--no-owner', '--no-acl', '--schema=public',
               '--exclude-table=public.alembic_version', '-h', url.host or 'localhost',
               '-p', str(url.port or 5432), '-U', url.username, '-d', url.database]
    result = subprocess.run(command, env={**os.environ, 'PGPASSWORD': url.password or ''},
                            capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError('pg_dump failed; check PostgreSQL version and database access.')
    # Remove psql-only random restriction markers so asyncpg can also restore the trusted snapshot.
    schema = '\n'.join(line for line in result.stdout.splitlines()
                       if not line.startswith(('\\restrict ', '\\unrestrict ')))
    schema = schema.replace('CREATE SCHEMA public;', 'CREATE SCHEMA IF NOT EXISTS public;')
    metadata = '\nCREATE TABLE public.alembic_version (version_num varchar(32) NOT NULL PRIMARY KEY);\n'
    for row in revisions:
        metadata += f"INSERT INTO public.alembic_version (version_num) VALUES ('{row['version_num']}');\n"
    header = ('-- Tipro: full EMPTY database schema; no users, passwords, tokens or payments.\n'
              '-- Restore only into an empty PostgreSQL 18 database.\n'
              '-- Generated by npm run db:schema. Migration revision is included at the end.\n\n')
    output = ROOT / 'schema/tipro.sql'
    output.write_text(header + schema + metadata)
    print('Saved backend/schema/tipro.sql (schema and migration version only; no private data).')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bin-dir', default=os.environ.get('TIPRO_PG_BIN'))
    try:
        asyncio.run(export(parser.parse_args()))
    except Exception:
        # Driver/config errors can contain credentials; keep them out of terminal output.
        print('Schema export failed. Check backend/.env, PostgreSQL access and TIPRO_PG_BIN.', file=sys.stderr)
        sys.exit(1)
